import assert from 'node:assert/strict'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import React from 'react'
import { createServer } from 'vite'
import { Window } from 'happy-dom'

const dom = new Window({ url: 'http://localhost:5173' })
const globals = { window: dom, document: dom.document, navigator: dom.navigator, HTMLElement: dom.HTMLElement, Node: dom.Node, IS_REACT_ACT_ENVIRONMENT: true }
const previous = new Map(Object.keys(globals).map(key => [key, Object.getOwnPropertyDescriptor(globalThis, key)]))
for (const [key, value] of Object.entries(globals)) Object.defineProperty(globalThis, key, { configurable: true, writable: true, value })
const server = await createServer({ root: path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..'), server: { middlewareMode: true, hmr: false } })
const { createRoot } = await import('react-dom/client')
const host = document.createElement('div'); document.body.append(host)
const root = createRoot(host)
try {
  const { readMacroPreferences, saveMacroPreferences, selectMacroMetric } = await server.ssrLoadModule('./src/market-data/indicators/macro/macro-preferences.ts')
  const { defaultMacroCategories, macroLanes, macroLayout, macroCategory, macroCategories, macroSelection, patchMacroLayout, moveMacroRow, deleteMacroCategory } = await server.ssrLoadModule('./src/market-data/indicators/macro/macro-layout.ts')
  const { createMacroLaneControls } = await server.ssrLoadModule('./src/market-data/indicators/macro/macro-lane-controls.ts')
  assert.equal(macroLayout(readMacroPreferences('USDX')).hideLegend, true, 'Hide Legend is ticked by default')
  let preferences = patchMacroLayout(readMacroPreferences('USDX'), { laneMode: true })
  assert.deepEqual(macroLanes(preferences).groups.find(group => group.id === 'labor').keys, ['payrolls', 'unemployment'])
  assert.deepEqual(macroLanes(preferences).groups.find(group => group.id === 'inflation').keys, ['headlineCpi', 'coreCpi'])
  const shell = document.createElement('div'); host.append(shell)
  let draws = 0, commits = 0
  const update = next => { commits++; preferences = next; position() }
  const controls = createMacroLaneControls(shell, () => draws++, update)
  const rows = ['rate', 'payrolls', 'unemployment', 'headlineCpi', 'coreCpi'].map(key => {
    const item = document.createElement('div'), axisButton = document.createElement('button')
    axisButton.dataset.macroAxis = key; item.append(axisButton); return { key, item, axisButton }
  })
  controls.setRows(rows)
  const position = () => controls.position(preferences, 900, 400, 30, 0)
  position()
  assert.equal(shell.querySelector('.macro-series-drawer').hidden, true)
  controls.toggleDrawer()
  assert.equal(shell.querySelector('.macro-series-drawer').hidden, false)
  assert.ok(rows.every(row => row.item.closest('.macro-series-drawer')))
  assert.equal(shell.querySelector('.macro-inline-layer [data-macro-axis]'), null, 'Plot labels never contain visibility controls')
  assert.equal(shell.querySelector('.macro-inline-layer').textContent, '', 'Event and category names live only in the drawer')
  const drawer = shell.querySelector('.macro-series-drawer'), body = shell.querySelector('.macro-drawer-body')
  const title = shell.querySelector('[aria-label="Move MFDI series window"]')
  Object.defineProperty(drawer, 'offsetHeight', { configurable: true, value: 180 })
  const windowPointer = (target, type, x, y) => target.dispatchEvent(new dom.PointerEvent(type, { bubbles: true, cancelable: true, button: 0, clientX: x, clientY: y, pointerId: 1 }))
  const initialWindow = { x: parseFloat(drawer.style.left), y: parseFloat(drawer.style.top) }, initialCommits = commits
  windowPointer(title, 'pointerdown', 700, 10)
  windowPointer(window, 'pointermove', 580, 40)
  windowPointer(window, 'pointerup', 580, 40)
  assert.equal(parseFloat(drawer.style.left), initialWindow.x - 120)
  assert.equal(parseFloat(drawer.style.top), initialWindow.y + 30)
  position()
  assert.equal(parseFloat(drawer.style.left), initialWindow.x - 120, 'Chart redraws keep the dragged window position')
  const movedLeft = drawer.style.left
  windowPointer(title, 'pointerdown', 580, 40); windowPointer(window, 'pointermove', 620, 90)
  title.dispatchEvent(new dom.KeyboardEvent('keydown', { key: 'Escape', bubbles: true }))
  windowPointer(window, 'pointerup', 620, 90)
  assert.equal(drawer.style.left, movedLeft, 'Escape cancels window dragging without closing it')
  assert.equal(drawer.hidden, false)
  assert.equal(commits, initialCommits, 'Moving the window never writes chart or event preferences')
  windowPointer(title, 'pointerdown', 580, 40); windowPointer(window, 'pointermove', -2000, -2000); windowPointer(window, 'pointerup', -2000, -2000)
  assert.equal(drawer.style.left, '0px'); assert.equal(drawer.style.top, '0px', 'Window bounds keep its title reachable')
  title.dispatchEvent(new dom.KeyboardEvent('keydown', { key: 'ArrowRight', bubbles: true, cancelable: true }))
  assert.equal(drawer.style.left, '10px')
  controls.toggleDrawer(false); controls.toggleDrawer(true); assert.equal(drawer.style.left, '10px')
  Object.defineProperty(body, 'scrollHeight', { configurable: true, value: 800 })
  Object.defineProperty(body, 'clientHeight', { configurable: true, value: 100 })
  let chartWheels = 0
  const chartWheel = () => chartWheels++
  shell.addEventListener('wheel', chartWheel)
  const beforeScrollY = controls.y('rate')
  const listWheel = new dom.WheelEvent('wheel', { bubbles: true, cancelable: true, deltaY: 70 })
  rows[0].axisButton.dispatchEvent(listWheel)
  assert.equal(body.scrollTop, 70, 'Wheel over the list scrolls the list')
  assert.equal(listWheel.defaultPrevented, true)
  title.dispatchEvent(new dom.WheelEvent('wheel', { bubbles: true, cancelable: true, deltaY: 2000 }))
  assert.equal(body.scrollTop, 700, 'Wheel over the window header scrolls the list and clamps at its bottom')
  title.dispatchEvent(new dom.WheelEvent('wheel', { bubbles: true, cancelable: true, deltaY: -2, deltaMode: 1 }))
  assert.equal(body.scrollTop, 668, 'Line-mode wheel input is supported')
  assert.equal(chartWheels, 0, 'Popover wheels cannot reach the native chart or change its zoom')
  assert.equal(controls.y('rate'), beforeScrollY, 'Popover scrolling leaves the plotted lanes in place')
  shell.removeEventListener('wheel', chartWheel)
  const original = preferences
  update(patchMacroLayout(preferences, { collapsed: ['inflation'] }))
  for (const [kind, field] of [['visibility', 'visible'], ['forecast', 'forecastVisible'], ['numbers', 'numbersVisible']]) {
    update({ ...preferences, series: { ...preferences.series, rate: { ...preferences.series.rate, [field]: true }, coreCpi: { ...preferences.series.coreCpi, [field]: false } } })
    const button = shell.querySelector(`[data-macro-all="${kind}"]`)
    assert.equal(button.getAttribute('aria-pressed'), 'mixed')
    button.click()
    assert.ok(rows.every(row => !preferences.series[row.key][field]), `${kind}: one click hides all selected rows including collapsed ones`)
    assert.equal(button.getAttribute('aria-pressed'), 'false')
    button.click()
    assert.ok(rows.every(row => preferences.series[row.key][field]), `${kind}: the next click enables all selected rows`)
    assert.equal(button.getAttribute('aria-pressed'), 'true')
  }
  update(original)
  shell.querySelector('.macro-inline-layer').getBoundingClientRect = () => ({ top: 30, left: 0, width: 900, height: 370 })
  const pointer = (target, type, y) => target.dispatchEvent(new dom.PointerEvent(type, { bubbles: true, button: 0, clientY: y, pointerId: 1 }))
  const startY = controls.y('payrolls'), otherY = controls.y('unemployment')
  const inflation = macroLanes(preferences).groups.find(group => group.id === 'inflation')
  pointer(rows[1].axisButton, 'pointerdown', startY)
  pointer(window, 'pointermove', 30 + inflation.top + 35)
  assert.notEqual(controls.y('payrolls'), startY, 'Dragging a row previews movement before committing')
  assert.equal(controls.y('unemployment'), otherY, 'A row drag leaves its peers in place')
  pointer(window, 'pointerup', 30 + inflation.top + 35)
  assert.equal(macroCategory(preferences, 'payrolls'), 'inflation', 'Dropping snaps the event into its target category')
  let axisClicks = 0
  rows[1].axisButton.onclick = () => { axisClicks++ }
  rows[1].axisButton.click()
  assert.equal(axisClicks, 0, 'The browser click after a drag cannot overwrite the saved drop with stale axis-selection state')
  pointer(rows[1].axisButton, 'pointerdown', controls.y('payrolls'))
  pointer(window, 'pointerup', controls.y('payrolls'))
  rows[1].axisButton.click()
  assert.equal(axisClicks, 1, 'An ordinary click still selects the axis')
  const beforeGroup = controls.y('unemployment'), beforePeer = controls.y('coreCpi')
  const header = shell.querySelector('[aria-label="Collapse Labor"]')
  const labor = macroLanes(preferences).groups.find(group => group.id === 'labor')
  pointer(header, 'pointerdown', 30 + labor.top)
  pointer(window, 'pointermove', 330)
  assert.notEqual(controls.y('unemployment'), beforeGroup, 'Dragging a category moves all of its rows during the preview')
  assert.equal(controls.y('coreCpi'), beforePeer, 'Other categories do not move with the dragged band')
  pointer(window, 'pointerup', 330)
  assert.notEqual(macroCategories(preferences).findIndex(group => group.id === 'labor'), 1, 'Dropping snaps the whole category into its new order')
  const inflationHeading = shell.querySelector('[aria-label="Collapse Inflation"]')
  assert.equal(inflationHeading.parentElement.querySelectorAll('button').length, 1, 'Arrow and category text share one control')
  const beforeCollapse = rows.map(row => controls.y(row.key)), beforeCollapseHeight = macroLanes(preferences).height
  inflationHeading.querySelector('span:last-child').click()
  assert.deepEqual(rows.map(row => controls.y(row.key)), beforeCollapse, 'Folding a category never hides or shifts plotted lines')
  assert.equal(macroLanes(preferences).height, beforeCollapseHeight, 'Folding the drawer preserves the plot canvas and scrollbar')
  assert.equal(rows[4].item.style.display, 'none', 'Collapsing folds only the drawer children')
  assert.equal(preferences.layout.categoryTarget, 'inflation')
  assert.equal(shell.querySelector('[aria-label="Expand Inflation"]').getAttribute('aria-pressed'), 'true')
  const selectedChildren = macroSelection(preferences)
  assert.deepEqual(new Set(selectedChildren), new Set(['payrolls', 'headlineCpi', 'coreCpi']))
  const beforeCategory = rows.map(row => controls.y(row.key))
  controls.startPlotDrag(new dom.PointerEvent('pointerdown', { button: 0, clientY: 100 }), false)
  pointer(window, 'pointermove', 125)
  rows.forEach((row, index) => assert.equal(controls.y(row.key), beforeCategory[index] + (selectedChildren.includes(row.key) ? 25 : 0), 'The selected collapsed category moves every child and leaves other categories fixed'))
  pointer(window, 'pointerup', 125)
  selectedChildren.forEach(key => assert.equal(preferences.layout.rowOffsets[key], 25))
  assert.equal(preferences.layout.rowOffsets.rate, undefined)
  shell.querySelector('[aria-label="Expand Inflation"]').click()
  assert.notEqual(controls.y('coreCpi'), null)
  pointer(rows[4].axisButton, 'pointerdown', controls.y('coreCpi'))
  pointer(window, 'pointermove', 160)
  const beforeCancel = commits
  window.dispatchEvent(new dom.KeyboardEvent('keydown', { key: 'Escape' }))
  pointer(window, 'pointerup', 160)
  assert.equal(commits, beforeCancel, 'Escape cancels a drag without saving')
  update(selectMacroMetric(preferences, 'rate'))
  assert.equal(preferences.layout.categoryTarget, undefined, 'Selecting an event clears category selection')
  const selectedBefore = controls.y('rate'), untouchedBefore = controls.y('coreCpi')
  controls.startPlotDrag(new dom.PointerEvent('pointerdown', { button: 0, clientY: 100 }), false)
  pointer(window, 'pointermove', 63)
  assert.equal(controls.y('rate'), selectedBefore - 37, 'Unlocked plot dragging freely previews only the selected straight line')
  assert.equal(controls.y('coreCpi'), untouchedBefore)
  pointer(window, 'pointerup', 63)
  assert.equal(preferences.layout.rowOffsets.rate, -37)
  assert.equal(controls.y('rate'), selectedBefore - 37, 'Free movement is retained instead of snapping to a category')
  assert.equal(macroCategory(preferences, 'rate'), 'policy')
  const noDragCommit = commits
  controls.startPlotDrag(new dom.PointerEvent('pointerdown', { button: 0, clientY: 100 }), false)
  pointer(window, 'pointermove', 150); pointer(window, 'pointercancel', 150); pointer(window, 'pointerup', 150)
  assert.equal(commits, noDragCommit, 'Cancelled selected-line drags leave the saved placement unchanged')
  const snapped = moveMacroRow(preferences, 'rate', 'policy')
  assert.equal(snapped.layout.rowOffsets.rate, undefined, 'Dragging a drawer row to a category restores its magnet position')
  const allKeys = rows.map(row => row.key), beforeAll = allKeys.map(key => controls.y(key))
  controls.startPlotDrag(new dom.PointerEvent('pointerdown', { button: 0, clientY: 100 }), true)
  pointer(window, 'pointermove', 145)
  allKeys.forEach((key, index) => assert.equal(controls.y(key), beforeAll[index] + 45, 'Linked preview moves every lane together'))
  pointer(window, 'pointerup', 145)
  assert.equal(preferences.layout.laneOffset, 45)
  const beforeZoom = allKeys.map(key => controls.y(key)), oldSpacing = macroLayout(preferences).laneSpacing
  const zoom = new dom.WheelEvent('wheel', { clientY: beforeZoom[0], deltaY: 100, cancelable: true })
  Object.defineProperty(zoom, 'clientY', { value: beforeZoom[0] })
  controls.zoomAll(zoom)
  const ratio = macroLayout(preferences).laneSpacing / oldSpacing
  allKeys.forEach((key, index) => assert.ok(Math.abs(controls.y(key) - (beforeZoom[0] + (beforeZoom[index] - beforeZoom[0]) * ratio)) < 1e-7, `Spacing zoom ${key}: ${controls.y(key)} vs ${beforeZoom[0] + (beforeZoom[index] - beforeZoom[0]) * ratio}; anchor ${zoom.clientY}; old ${beforeZoom[0]}`))
  assert.equal(zoom.defaultPrevented, true)
  controls.fitAll()
  assert.equal(preferences.layout.laneOffset, 0)
  assert.deepEqual(preferences.layout.rowOffsets, {}, 'Fit all restores the category arrangement')
  assert.ok(allKeys.every(key => controls.y(key) >= 30 && controls.y(key) <= 400), 'Fit all lanes brings the expanded collection into the available pane')
  update(patchMacroLayout(preferences, { laneMode: false }))
  shell.querySelector('[aria-label="Collapse Labor"] span:last-child').click()
  assert.equal(rows[2].item.style.display, 'none', 'Category text collapses drawer rows in numerical view too')
  shell.querySelector('[aria-label="Expand Labor"] span:last-child').click()
  assert.equal(rows[2].item.style.display, 'flex')
  update(patchMacroLayout(preferences, { laneMode: true }))
  shell.querySelector('[aria-label="Close MFDI series drawer"]').click()
  assert.equal(shell.querySelector('.macro-series-drawer').hidden, true)
  assert.ok(draws > 0)
  controls.destroy()
  assert.equal(shell.querySelector('.macro-inline-layer'), null)

  preferences = { ...preferences, categories: [...macroCategories(preferences), { id: 'custom', label: 'My releases' }] }
  preferences = moveMacroRow(preferences, 'coreCpi', 'custom')
  preferences = deleteMacroCategory(preferences, 'custom')
  assert.equal(macroCategory(preferences, 'coreCpi'), 'uncategorized', 'Deleting a category retains its event under Uncategorized')
  preferences = patchMacroLayout(preferences, { hideLegend: true, collapsed: ['labor'], rowOffsets: { coreCpi: -13.25, rate: 40 } })
  saveMacroPreferences(preferences, 'USDX')
  assert.deepEqual(readMacroPreferences('USDX'), preferences, 'Categories, assignments, row order, collapse, lane view and Hide Legend survive refresh')
  assert.equal(macroLayout(readMacroPreferences('EURUSD')).hideLegend, true, 'Other symbols start with Hide Legend ticked')
  saveMacroPreferences(patchMacroLayout(readMacroPreferences('EURUSD'), { hideLegend: false }), 'EURUSD')
  assert.equal(macroLayout(readMacroPreferences('EURUSD')).hideLegend, false, 'An explicitly saved unticked choice survives refresh')
  assert.equal(readMacroPreferences('EURUSD').categoryByEvent.payrolls, 'inflation', 'Category membership is shared with remembered event selections')

  const { MacroSettingsDialog } = await server.ssrLoadModule('./src/market-data/indicators/macro/MacroSettingsDialog.tsx')
  let saved
  await React.act(async () => root.render(React.createElement(MacroSettingsDialog, { preferences, onSave: next => { saved = next }, onClose() {} })))
  const hide = host.querySelector('[aria-label="Hide MFDI Legend"]')
  assert.equal(hide.checked, true)
  await React.act(async () => hide.click())
  await React.act(async () => host.querySelector('form').dispatchEvent(new dom.Event('submit', { bubbles: true, cancelable: true })))
  assert.equal(saved.layout.hideLegend, false)
  assert.equal(preferences.layout.hideLegend, true, 'Hide Legend edits use the existing draft save/cancel boundary')
  await React.act(async () => root.render(null))
  const reordered = { ...patchMacroLayout(preferences, { categoryOrder: ['inflation', 'labor', 'policy'] }), categories: defaultMacroCategories }
  await React.act(async () => root.render(React.createElement(MacroSettingsDialog, { preferences: reordered, onSave: next => { saved = next }, onClose() {} })))
  const rename = host.querySelector('[aria-label="Category name inflation"]')
  const reactProps = rename[Object.getOwnPropertyNames(rename).find(key => key.startsWith('__reactProps$'))]
  await React.act(async () => reactProps.onChange({ target: { value: 'Price releases' } }))
  await React.act(async () => host.querySelector('form').dispatchEvent(new dom.Event('submit', { bubbles: true, cancelable: true })))
  assert.deepEqual(saved.categories.map(category => category.id), defaultMacroCategories.map(category => category.id), 'Renaming a shared category does not overwrite another symbol\'s presentation order')
  assert.equal(saved.layout.categoryOrder[0], 'inflation')
  const { createMacroTooltip } = await server.ssrLoadModule('./src/market-data/indicators/macro/macro-tooltip.ts')
  const tooltip = createMacroTooltip(host)
  const reading = { id: 'one', time: 1, releasedAt: Date.UTC(2026, 10, 10, 18), value: 0.3, previous: 0.3, unit: 1, impact: 'positive' }
  tooltip.show('coreCpi', reading, 0.2, () => 'Nov 11, 2026 01:00 AM')
  assert.deepEqual([...tooltip.element.querySelectorAll('th')].map(node => node.textContent), ['Actual', 'Forecast', 'Previous'])
  assert.deepEqual([...tooltip.element.querySelectorAll('td')].map(node => node.textContent), ['0.30%', '0.20%', '0.30%'])
  assert.equal(tooltip.element.querySelector('time').textContent, 'Nov 11, 2026 01:00 AM', 'Tooltip uses the app clock formatter rather than guessing the timezone')
  tooltip.position(50, 100, 200, 900, 600)
  assert.match(host.querySelector('.macro-tooltip-connector path').getAttribute('d'), /^M50 300 L/)
  tooltip.show('payrolls', { ...reading, value: 0, previous: null, unit: 4, multiplier: 1 }, null, String)
  assert.deepEqual([...tooltip.element.querySelectorAll('td')].map(node => node.textContent), ['0k', '—', '—'], 'Zero is a value; missing forecast/previous stay blank')
  tooltip.hide(); assert.equal(tooltip.element.hidden, true)
  assert.equal(host.querySelector('.macro-tooltip-connector').style.display, 'none')
  tooltip.destroy()
  console.log('✓ MFDI lanes: default/custom categories, row snap and whole-band drag previews, reorder/collapse, cancellation/cleanup, deletion retention, symbol-specific layout and shared currency membership persistence')
} finally {
  await React.act(async () => root.unmount()); await server.close(); await dom.happyDOM.close()
  for (const [key, descriptor] of previous) { if (descriptor) Object.defineProperty(globalThis, key, descriptor); else delete globalThis[key] }
}
