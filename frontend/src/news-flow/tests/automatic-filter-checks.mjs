import assert from 'node:assert/strict'

export async function checkAutomaticFilters({ server, dom, root, React, control, pending, reply, click, requests, timers }) {
  const { useNewsSettings } = await server.ssrLoadModule('./src/news-flow/settings.ts')
  const { readNewsSettings, newsQuery } = await server.ssrLoadModule('./src/news-flow/model.ts')
  const { encodeFilterPolicy, defaultFilterPolicy } = await server.ssrLoadModule('./src/news-flow/filter-policy.ts')
  const { NewsGlobalSettings } = await server.ssrLoadModule('./src/news-flow/NewsGlobalSettings.tsx')
  const { NewsSoundAlerts } = await server.ssrLoadModule('./src/news-flow/NewsSoundAlerts.tsx')
  const original = dom.localStorage.getItem('fyodor.news-flow.v1')
  const headline = 'Indonesian Rupiah gains as US Dollar weakens amid Treasury sell-off'
  function Harness() {
    const [settings, change] = useNewsSettings()
    return React.createElement(React.Fragment, null, React.createElement(NewsSoundAlerts), React.createElement(NewsGlobalSettings, { settings, onChange: change }))
  }
  async function change(label, value) {
    await React.act(async () => {
      const input = control(label)
      Object.getOwnPropertyDescriptor(dom.HTMLInputElement.prototype, 'value').set.call(input, value)
      input.dispatchEvent(new dom.Event('input', { bubbles: true })); input.dispatchEvent(new dom.Event('change', { bubbles: true }))
    })
  }
  try {
    dom.localStorage.setItem('fyodor.news-flow.v1', JSON.stringify({ ...readNewsSettings(), marketRelevance: true, automaticFilters: { ...defaultFilterPolicy } }))
    await React.act(async () => root.render(React.createElement(Harness)))
    await reply(requests.findLast(request => !request.answered && !request.signal?.aborted && request.url === '/storage-api/news-flow/notifications'), { mode: 'included', max_age_seconds: 86400, unified_alerts: true, connection: null, error: '', last_sent: null })
    assert.equal(JSON.parse(pending('/notifications/rules').body).filter_policy, '{}')
    await reply(pending('/notifications/rules'), { mode: 'included' })
    await reply(pending('/arrivals'), { cursor: 20, items: [] })
    await click('Include keywords: Currencies')
    assert.ok(control('Remove include keyword USD'))
    assert.equal(control('Remove include keyword Nvidia'), null)
    await click('Include keywords: Bonds and funding')
    assert.ok(control('Remove include keyword Treasury'))
    assert.equal(control('Remove include keyword USD'), null)
    await change('Include keyword input', 'Nvidia')
    assert.ok(control('Remove include keyword Nvidia'), 'Typing searches across groups')
    assert.equal(control('Add include keyword').disabled, true, 'Duplicate prevention remains global')
    await change('Include keyword input', '')
    await click('Include keywords: Custom')
    assert.ok(control('Remove include keyword MY CUSTOM PHRASE'))
    const includeBefore = readNewsSettings().include
    await click('Other-market exceptions keywords: Bonds and funding')
    assert.ok(control('Remove other-market exceptions keyword Treasury'))
    assert.ok(control('Remove other-market filter keyword indonesian'))
    const timer = [...timers].find(([, value]) => value.ms === 1000)
    await React.act(async () => { timers.delete(timer[0]); timer[1].fn() })
    const stale = pending('/arrivals')
    await click('Hide other-market domestic news')
    assert.equal(stale.signal.aborted, true)
    assert.equal(readNewsSettings().automaticFilters.other_markets, false)
    assert.equal(JSON.parse(JSON.parse(pending('/notifications/rules').body).filter_policy).other_markets, false)
    const query = new URLSearchParams(newsQuery(readNewsSettings(), [], 0, null, null))
    assert.equal(JSON.parse(query.get('filter_policy')).other_markets, false)
    await reply(pending('/notifications/rules'), { mode: 'included' })
    assert.equal(new URL(pending('/arrivals').url, 'http://localhost').searchParams.get('after'), '20')
    await reply(stale, { cursor: 21, items: [] })
    await reply(pending('/arrivals'), { cursor: 21, items: [] })
    await click('Remove other-market filter keyword indonesian')
    assert.equal(readNewsSettings().automaticFilters.other_market_terms.split(', ').includes('indonesian'), false)
    await click('Remove other-market exceptions keyword Treasury')
    assert.equal(readNewsSettings().automaticFilters.exceptions.split(', ').includes('Treasury'), false)
    assert.equal(readNewsSettings().include, includeBefore)
    await click('Reset automatic filters')
    assert.equal(encodeFilterPolicy(readNewsSettings().automaticFilters), '{}')
    assert.equal(readNewsSettings().include, includeBefore, 'Reset preserves user keywords')
    await change('Check headline text', headline)
    await click('Check headline')
    const checked = pending('/classify'), payload = JSON.parse(checked.body)
    assert.equal(payload.title, headline); assert.equal(payload.filter_policy, '{}')
    await reply(checked, { relevance: { tier: 'included', reason: 'Included · cross-market exception · Treasury' }, matched_include: ['dollar', 'Treasury'], matched_exclude: [] })
    assert.match(dom.document.body.textContent, /Include matches: dollar, Treasury/)
    assert.match(dom.document.body.textContent, /cross-market exception · Treasury/)
    await click('Check headline')
    const invalidated = pending('/classify')
    await click('Keep cross-market drivers')
    assert.equal(invalidated.signal.aborted, true)
    assert.equal(control('Check headline text').value, headline)
    await reply(invalidated, { relevance: { tier: 'included', reason: 'Stale decision' }, matched_include: [], matched_exclude: [] })
    assert.doesNotMatch(dom.document.body.textContent, /Stale decision/)
    await click('Trading relevance')
    assert.equal(control('Hide other-market domestic news').disabled, true)
    assert.match(dom.document.body.textContent, /Automatic filters are bypassed/)
    assert.equal(readNewsSettings().automaticFilters.cross_market, false)
    await click('Check headline')
    assert.equal(JSON.parse(pending('/classify').body).market_relevance, false)
    await React.act(async () => root.render(null))
    assert.equal(pending('/classify'), undefined)
    assert.equal(timers.size, 0)
    console.log('✓ Automatic filters: grouped/searchable tags, exposed lists, persisted controls, shared reading/delivery scope, cursor continuity, authoritative preview and cleanup')
  } finally {
    await React.act(async () => root.render(null))
    if (original === null) dom.localStorage.removeItem('fyodor.news-flow.v1'); else dom.localStorage.setItem('fyodor.news-flow.v1', original)
  }
}
